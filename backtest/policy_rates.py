def rate_series(ccy: str, index: pd.DatetimeIndex) -> pd.Series:
    """Daily policy-rate series ffilled onto `index` (as-of month start of
    the following month -> conservatively lagged: a change dated 'YYYY-MM'
    takes effect on the FIRST day of the NEXT month, so no intra-month
    lookahead is possible)."""
    pts = RATE_CHANGES[ccy]
    ts = [pd.Timestamp(m, tz="UTC") + pd.DateOffset(months=1) for m, _ in pts]
    s = pd.Series([v for _, v in pts], index=pd.DatetimeIndex(ts))
    return s.reindex(s.index.union(index)).ffill().reindex(index)
